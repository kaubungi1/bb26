/* 값 검증. 목록에 없는 문양과 #rrggbb 가 아닌 색은 한 글자도 통과시키지 않는다.
   이 값이 DB 에서 오므로, 그대로 SVG 에 꽂으면 주입이 된다. */
const CREST_HEX_RE = /^#[0-9a-f]{6}$/i;
function crestSafe(c) {
  if (!c || typeof c !== 'object') return null;
  const shape = CREST_SHAPES[c.shape] ? c.shape : null;
  if (!shape) return null;
  return {
    shape,
    bg: CREST_HEX_RE.test(c.bg || '') ? c.bg : '#00b8ad',
    fg: CREST_HEX_RE.test(c.fg || '') ? c.fg : '#ffffff',
  };
}

/* 육각 틀 + 문양 + 색 둘. size 는 화면에 그릴 픽셀 크기다.

   문양은 24×24 좌표계라 100×100 육각 안에 앉히려면 옮기고 키워야 한다.
   translate(50 50) scale(2.1) translate(-12 -12)  →  24 상자의 가운데(12,12)가 (50,50)에 온다.
   문양이 차지하는 폭은 24×2.1 = 50 이고 육각 가운데 폭이 88 이라 넉넉하다.
   그래도 육각으로 잘라낸다 — 모서리가 뾰족한 문양이 위아래로 삐져나오는 것을 막는다.

   clipPath 의 id 는 문서에 여러 문장이 있어도 겹치면 안 되므로 매번 새로 만든다. */
let crestSeq = 0;
function crestSvg(crest, size = 76) {
  const c = crestSafe(crest);
  if (!c) return '';
  const id = 'crest-clip-' + (++crestSeq);
  return `<svg class="crest-svg" viewBox="0 0 100 100" width="${size}" height="${size}" aria-hidden="true">` +
    `<defs><clipPath id="${id}"><polygon points="${CREST_HEX}" /></clipPath></defs>` +
    `<g clip-path="url(#${id})">` +
    `<polygon points="${CREST_HEX}" fill="${c.bg}" />` +
    `<g fill="none" stroke="${c.fg}" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"` +
    ` transform="translate(50 50) scale(2.1) translate(-12 -12)">` +
    `<path d="${CREST_SHAPES[c.shape]}" /></g></g></svg>`;
}

/* 주소로 미리 보기. ?crest=plane:00b8ad:ffffff
   저장된 값보다 이긴다 — 정하기 전에 눈으로 고르는 용도다. */
function crestFromQuery() {
  const v = new URLSearchParams(location.search).get('crest');
  if (!v) return null;
  const [shape, bg, fg] = v.split(':');
  return crestSafe({ shape, bg: '#' + (bg || ''), fg: '#' + (fg || '') });
}


/* 길드 하나의 표식. 사진을 올렸으면 사진이 먼저다 —
   프로필의 사진 > 이모지 > 첫 글자와 같은 규칙이고, 서른여섯 문양만으로는
   길드가 늘수록 같은 그림이 겹친다.
   사진도 육각으로 잘라 넣는다. 자를 때 이미 육각으로 오려 왔지만(crop.js),
   여기서 한 번 더 클립해야 옛 사진이나 다른 경로로 올라온 그림도 틀을 지킨다. */
function crestFor(guild, size = 76) {
  if (!guild) return '';
  if (guild.hasImage) {
    const id = 'crest-clip-' + (++crestSeq);
    const url = `/api/guilds/${encodeURIComponent(guild.slug)}/image`;
    return `<svg class="crest-svg" viewBox="0 0 100 100" width="${size}" height="${size}" aria-hidden="true">`
      + `<defs><clipPath id="${id}"><polygon points="${CREST_HEX}" /></clipPath></defs>`
      + `<image href="${url}" x="0" y="0" width="100" height="100"`
      + ` preserveAspectRatio="xMidYMid slice" clip-path="url(#${id})" /></svg>`;
  }
  return crestSvg(guild.style?.crest, size);
}
